import assert from 'node:assert/strict';
import {handle, fixedTimeEqual} from '../worker/refresh-worker.mjs';

const ROOT='https://houselens-refresh.example.workers.dev';
const ORIGIN='https://kristina-abrahamyan.github.io';
const secret='a-private-long-access-code-not-in-git';
const env={GITHUB_TOKEN:'TEST_GITHUB_TOKEN',REFRESH_ACCESS_CODE:secret};
const mk=(path,method='GET',body=null,headers={})=>new Request(ROOT+path,{method,headers:{Origin:ORIGIN,'X-HouseLens-Access':secret,...(body?{'Content-Type':'application/json'}:{}),...headers},...(body?{body:JSON.stringify(body)}:{})});
const run=(status='completed',date=new Date().toISOString(),event='workflow_dispatch')=>({id:99,status,conclusion:status==='completed'?'success':null,created_at:date,event,html_url:'https://github.com/kristina-abrahamyan/houselens/actions/runs/99'});
let calls=[];let listing=[];
global.fetch=async(url,init)=>{
  calls.push({url,init});
  assert.equal(init.headers.Authorization,'Bearer TEST_GITHUB_TOKEN');
  if(url.endsWith('/dispatches'))return new Response(JSON.stringify({workflow_run_id:100,html_url:'https://github.com/kristina-abrahamyan/houselens/actions/runs/100'}),{status:200});
  if(url.includes('/runs?'))return Response.json({workflow_runs:listing});
  if(url.endsWith('/runs/99'))return Response.json(run('completed'));
  throw Error('Unexpected URL');
};
const response=async request=>{const r=await handle(request,env);return {status:r.status,body:r.status===204?null:await r.json(),headers:r.headers};};
assert.equal(fixedTimeEqual(secret,secret),true);
assert.equal(fixedTimeEqual(secret,'different'),false);
assert.equal(fixedTimeEqual('',null),false);
assert.equal((await response(mk('/refresh','POST',{listings:false},{Origin:'https://bad.site'}))).status,403);
assert.equal((await response(mk('/refresh','POST',{listings:false},{'X-HouseLens-Access':'bad'}))).status,401);
assert.equal((await response(mk('/refresh','POST',{listings:false}))).status,202);
assert.equal(calls.length,2);
assert.equal(calls[1].init.method,'POST');
assert.deepEqual(JSON.parse(calls[1].init.body).inputs,{refresh_listings:'false'});
assert.equal((await response(mk('/refresh','POST',{listings:true}))).status,202);
assert.deepEqual(JSON.parse(calls[3].init.body).inputs,{refresh_listings:'true'});
assert.equal((await response(mk('/refresh','POST',{listings:'yes'}))).status,400);
listing=[run('in_progress')];
assert.equal((await response(mk('/refresh','POST',{listings:false}))).status,409);
assert.equal((await response(mk('/status'))).body.status,'in_progress');
listing=[run('completed',new Date().toISOString())];
assert.equal((await response(mk('/refresh','POST',{listings:false}))).status,429);
listing=[run('completed',new Date(Date.now()-20*60*1000).toISOString())];
const s=(await response(mk('/status')));assert.equal(s.body.runId,99);assert.equal(s.headers.get('Access-Control-Allow-Origin'),ORIGIN);
assert.equal((await response(mk('/status?runId=99'))).body.runId,99);
assert.equal((await response(mk('/status?runId=bad'))).status,400);
assert.equal((await response(mk('/refresh','OPTIONS'))).status,204);
assert.equal((await response(mk('/bad'))).status,404);
assert.equal((await response(mk('/status','POST',{listings:false}))).status,405);
assert.equal((await handle(mk('/status'),{GITHUB_TOKEN:'',REFRESH_ACCESS_CODE:secret})).status,503);
assert.equal((await response(mk('/refresh','POST',{listings:false}))).body.accepted,true);
console.log('Worker auth, CORS, dispatch, status and cooldown tests passed.');
